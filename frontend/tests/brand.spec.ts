import { expect, test } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
import type { Project, Snapshot } from '../src/types';

test('identité Vanguard locale et écrans du banc conservés', async ({ page, request }, testInfo) => {
  test.setTimeout(60_000);
  const { token } = await (await request.get('/api/session')).json();
  const change = (path: string, data: unknown = {}) => request.post(`/api${path}`, { headers: { 'X-FAT-Token': token }, data });
  const state = async (): Promise<Snapshot> => (await request.get('/api/state')).json();
  if (['running', 'paused', 'error'].includes((await state()).status)) expect((await change('/run/stop')).ok()).toBeTruthy();
  expect((await change('/pilot/load')).ok()).toBeTruthy();
  const project: Project = await (await request.get('/api/project')).json();
  const errors: string[] = [], external: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', event => { if (new URL(event.url()).hostname !== '127.0.0.1') external.push(event.url()); });
  page.on('dialog', dialog => dialog.accept());
  await page.goto('/');
  await expect(page.getByLabel('Nom du projet')).toHaveValue(project.name);
  await expect(page).toHaveTitle('Vanguard FAT Studio — Banc de simulation local');
  await expect(page.getByLabel('Vanguard FAT Studio', { exact: true })).toBeVisible();
  const brand = await page.locator('.brand-wordmark').evaluate(async element => {
    const logo = element as HTMLImageElement;
    await logo.decode();
    await document.fonts.ready;
    return { naturalWidth: logo.naturalWidth, naturalHeight: logo.naturalHeight, width: logo.clientWidth, height: logo.clientHeight, font: getComputedStyle(document.body).fontFamily, fontsLoaded: ['400 13px Geist', '700 13px Geist', '400 13px "Geist Mono"'].map(font => document.fonts.check(font)) };
  });
  expect(Math.abs(brand.width / brand.height - brand.naturalWidth / brand.naturalHeight)).toBeLessThan(.05);
  expect(brand.font).toContain('Geist');
  expect(brand.fontsLoaded).toEqual([true, true, true]);
  for (const name of ['favicon.png', 'logo_vanguard.png', 'logo_vanguard_wordmark_horizontal.png', 'logo_vanguard_wordmark_horizontal_white.png', 'Geist-Regular.ttf', 'Geist-Bold.ttf', 'GeistMono-Regular.ttf', 'OFL.txt']) expect((await request.get(`/brand/${name}`)).ok(), name).toBeTruthy();
  const shot = async (name: string, target?: string) => {
    const toast = page.getByRole('button', { name: 'Fermer la notification', exact: true });
    if (await toast.isVisible()) await toast.click();
    if (target) await page.locator(target).scrollIntoViewIfNeeded();
    await page.screenshot({ path: testInfo.outputPath(`${name}.png`) });
  };
  await expect(page.locator('.digital-control')).toHaveCount(40);
  await expect(page.locator('.analog-control')).toHaveCount(16);
  await shot('01-console');
  await page.getByRole('button', { name: 'Construire', exact: true }).click();
  await page.locator('.react-flow__node[data-id="TK101"]').click();
  await expect(page.getByLabel('Nom / repère', { exact: true })).toHaveValue(project.equipment.find(item => item.id === 'TK101')!.name);
  await shot('02-builder-animation');
  await page.getByRole('button', { name: 'Scénarios', exact: true }).click();
  await page.locator('.scenario-list-item').filter({ hasText: project.scenarios.find(scenario => scenario.execution_mode === 'guided')!.name }).click();
  await expect(page.locator('.guided-builder')).toBeVisible();
  await shot('03-guided-builder');
  await page.locator('.scenario-list-item').filter({ hasText: project.scenarios.find(scenario => scenario.execution_mode === 'timed')!.name }).click();
  await shot('04-timed-plan');
  await page.getByRole('button', { name: /^Variables & mapping/ }).click();
  await shot('05-mapping');
  await page.getByRole('button', { name: 'Connexion', exact: true }).click();
  await shot('06-connection');
  await page.getByRole('button', { name: 'Ouvrir', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await shot('07-workspaces-archive');
  await page.getByRole('button', { name: 'Fermer la fenêtre', exact: true }).click();
  await page.getByRole('button', { name: 'Nouveau', exact: true }).click();
  await shot('08-new-project');
  await page.getByRole('button', { name: 'Annuler', exact: true }).click();
  await page.getByRole('button', { name: 'P&ID', exact: true }).click();
  await page.locator('#active-scenario').selectOption('demo-guided-io');
  await page.getByRole('button', { name: 'Démarrer', exact: true }).click();
  await expect(page.locator('.status-badge')).toHaveText('En cours');
  await page.getByRole('button', { name: 'Exécuter STEP 1', exact: true }).click();
  await expect.poll(async () => (await state()).guided_steps?.[0]?.state).toBe('applied');
  await expect(page.getByLabel('Observation du testeur')).toBeEnabled();
  await shot('09-guided-applied', '.guided-current-step');
  expect((await state()).result.verdict).toBe('not_evaluated');
  await page.getByRole('button', { name: 'Tendances & rapport', exact: true }).click();
  await shot('10-trends-report');
  await page.getByRole('button', { name: 'Historique', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await shot('10b-history');
  await page.getByRole('button', { name: 'Fermer l’historique', exact: true }).click();
  await page.getByRole('button', { name: 'P&ID', exact: true }).click();
  await page.getByRole('button', { name: 'Mettre en pause', exact: true }).click();
  await expect(page.locator('.palette')).toBeVisible();
  await shot('11-paused-builder');
  await page.getByRole('button', { name: 'Arrêter l’essai', exact: true }).click();
  // Visual inspection of the confirmation only: no mapping or PLC is claimed.
  // The synthetic validation is scoped to this preview; run/start must never be called.
  await page.route('**/api/validate', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ valid: true, errors: [], warnings: [] }) }));
  let attemptedConnection = false;
  await page.route('**/api/run/start', route => { attemptedConnection = true; return route.abort(); });
  await page.getByRole('button', { name: 'Connexion', exact: true }).click();
  await page.getByRole('button', { name: /PLCSIM Advanced · OPC UA/ }).click();
  await page.getByLabel('Endpoint OPC UA', { exact: true }).fill('opc.tcp://127.0.0.1:4999');
  await page.getByLabel('Nom de la cible virtuelle approuvée', { exact: true }).fill('CIBLE-VISUELLE-SANS-CONNEXION');
  await page.getByRole('button', { name: 'Démarrer', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Confirmer la cible virtuelle');
  await shot('13-target-confirmation');
  await page.getByRole('button', { name: 'Annuler', exact: true }).click();
  expect(attemptedConnection).toBe(false);
  await page.unroute('**/api/validate');
  await page.unroute('**/api/run/start');
  await page.getByRole('button', { name: /Démonstration locale/ }).click();
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click();
  expect(errors).toEqual([]);
  expect(external).toEqual([]);
  await writeFile(testInfo.outputPath('brand-observations.json'), JSON.stringify({ brand, browser_errors: errors, external_requests: external, mode: 'temporary demo, port 8766; no PLC; no human observation' }, null, 2));
});

test('écran de démarrage Vanguard et erreur de service identifiés', async ({ page }, testInfo) => {
  await page.route('**/api/project', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Service temporairement indisponible pour le contrôle visuel.' }) }));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Vanguard FAT Studio', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Réessayer', exact: true })).toBeEnabled();
  await expect(page.locator('.boot-logo')).toHaveAttribute('src', '/brand/logo_vanguard.png');
  await page.screenshot({ path: testInfo.outputPath('12-boot-unavailable.png') });
});
